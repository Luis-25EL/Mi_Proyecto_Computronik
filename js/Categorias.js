/* =========================================================
                OFERTA RELÁMPAGO
                CUENTA REGRESIVA
========================================================= */

function iniciarCuentaRegresiva() {

    const horasElemento =
        document.getElementById("timer-horas");

    const minutosElemento =
        document.getElementById("timer-minutos");

    const segundosElemento =
        document.getElementById("timer-segundos");


    /* Verificar que existan los elementos */

    if (
        !horasElemento ||
        !minutosElemento ||
        !segundosElemento
    ) {
        return;
    }


    /*
        Crear una fecha de finalización.

        La oferta durará 5 horas,
        42 minutos y 18 segundos
        desde que se carga la página.
    */

    const ahora = new Date();

    const fechaFinal =
        new Date(
            ahora.getTime() +
            (
                12 * 60 * 60 * 1000 +
                42 * 60 * 1000 +
                18 * 1000
            )
        );


    /* =====================================================
                    ACTUALIZAR CONTADOR
    ===================================================== */

    function actualizarTemporizador() {

        const ahora = new Date();

        const diferencia =
            fechaFinal.getTime() -
            ahora.getTime();


        /* Si llegó a cero */

        if (diferencia <= 0) {

            horasElemento.textContent = "00";
            minutosElemento.textContent = "00";
            segundosElemento.textContent = "00";

            clearInterval(intervalo);

            return;
        }


        /* Calcular tiempo */

        const horas =
            Math.floor(
                diferencia / (1000 * 60 * 60)
            );


        const minutos =
            Math.floor(
                (diferencia % (1000 * 60 * 60)) /
                (1000 * 60)
            );


        const segundos =
            Math.floor(
                (diferencia % (1000 * 60)) /
                1000
            );


        /* Mostrar con dos dígitos */

        horasElemento.textContent =
            String(horas).padStart(2, "0");


        minutosElemento.textContent =
            String(minutos).padStart(2, "0");


        segundosElemento.textContent =
            String(segundos).padStart(2, "0");

    }


    /* Ejecutar inmediatamente */

    actualizarTemporizador();


    /* Actualizar cada segundo */

    const intervalo =
        setInterval(
            actualizarTemporizador,
            1000
        );

}


/* =========================================================
                INICIAR CUENTA REGRESIVA
========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    function () {

        iniciarCuentaRegresiva();

    }
);