/* =========================================================
                OBTENER TODOS LOS PRODUCTOS
========================================================= */

function obtenerTodosLosProductos() {

    let todosLosProductos = [];


    Object.keys(productosCategorias).forEach(categoria => {

        productosCategorias[categoria].forEach(producto => {

            todosLosProductos.push({

                ...producto,

                categoria: categoria

            });

        });

    });


    return todosLosProductos;

}


/* =========================================================
                    BUSCAR PRODUCTOS
========================================================= */

function buscarProductosCategorias() {

    if (!buscadorProductos) {
        return;
    }


    const texto =
        buscadorProductos.value
            .toLowerCase()
            .trim();


    /* Si está vacío */

    if (texto === "") {

        mostrarCategoria(
            window.categoriaActual || "laptops"
        );

        return;
    }


    /* Obtener todos */

    const todosLosProductos =
        obtenerTodosLosProductos();


    /* Filtrar */

    const resultados =
        todosLosProductos.filter(producto => {

            const nombre =
                producto.nombre.toLowerCase();


            const categoria =
                producto.categoria
                    .toLowerCase()
                    .replace("-", " ");


            return (
                nombre.includes(texto) ||
                categoria.includes(texto)
            );

        });


    /* Mostrar resultados */

    mostrarResultadosBusqueda(
        resultados,
        texto
    );

}


/* =========================================================
            MOSTRAR RESULTADOS DE BÚSQUEDA
========================================================= */

function mostrarResultadosBusqueda(
    resultados,
    texto
) {

    const titulo =
        document.getElementById(
            "categoriaTitulo"
        );

    const descripcion =
        document.getElementById(
            "categoriaDescripcion"
        );

    const etiqueta =
        document.getElementById(
            "categoriaEtiqueta"
        );


    /* Encabezado */

    etiqueta.textContent =
        "RESULTADOS DE BÚSQUEDA";


    titulo.textContent =
        `Resultados para: "${texto}"`;


    descripcion.textContent =
        `Se encontraron ${resultados.length} producto(s).`;


    /* Productos */

    mostrarProductosEnGrid(resultados);


    /* Ir hacia productos */

    document
        .getElementById("productosCategoria")
        .scrollIntoView({
            behavior: "smooth"
        });

}


