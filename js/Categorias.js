/* =========================================================
                    MOSTRAR CATEGORÍA
========================================================= */

function mostrarCategoria(categoria) {

    const contenedor =
        document.getElementById("contenedorProductosCategoria");

    const titulo =
        document.getElementById("categoriaTitulo");

    const descripcion =
        document.getElementById("categoriaDescripcion");

    const etiqueta =
        document.getElementById("categoriaEtiqueta");


    /* Verificar categoría */

    if (!productosCategorias[categoria]) {

        console.error("Categoría no encontrada:", categoria);

        return;
    }


    /* Guardar categoría actual */

    window.categoriaActual = categoria;


    /* Cambiar información */

    titulo.textContent =
        informacionCategorias[categoria].titulo;

    descripcion.textContent =
        informacionCategorias[categoria].descripcion;

    etiqueta.textContent =
        informacionCategorias[categoria].titulo.toUpperCase();


    /* Obtener productos */

    const productos =
        productosCategorias[categoria];


    /* Mostrar productos */

    mostrarProductosEnGrid(productos);


    /* Desplazarse hacia productos */

    document
        .getElementById("productosCategoria")
        .scrollIntoView({
            behavior: "smooth"
        });

}


/* =========================================================
              MOSTRAR PRODUCTOS EN EL GRID
========================================================= */

function mostrarProductosEnGrid(productos) {

    const contenedor =
        document.getElementById(
            "contenedorProductosCategoria"
        );


    /* Limpiar */

    contenedor.innerHTML = "";


    /* No hay resultados */

    if (!productos || productos.length === 0) {

        contenedor.innerHTML = `

            <div class="mensaje-sin-productos">

                <i class="fa-solid fa-box-open"></i>

                <h3>
                    No se encontraron productos
                </h3>

                <p>
                    Intenta realizar otra búsqueda.
                </p>

            </div>

        `;

        return;
    }


    /* Crear tarjetas */

    productos.forEach(producto => {

        const tarjeta =
            document.createElement("div");


        tarjeta.classList.add(
            "producto-categoria-card"
        );


        tarjeta.innerHTML = `

            <img
                src="${producto.imagen}"
                alt="${producto.nombre}"
                onerror="this.src='img/producto-default.jpg'"
            >

            <h3>
                ${producto.nombre}
            </h3>

            <div class="producto-categoria-precio">

                S/ ${producto.precio.toLocaleString(
                    "es-PE",
                    {
                        minimumFractionDigits: 2,
                        maximumFractionDigits: 2
                    }
                )}

            </div>

            <button
                onclick="agregarAlCarritoCategoria(
                    ${producto.id},
                    '${producto.nombre}',
                    ${producto.precio},
                    '${producto.imagen}'
                )">

                <i class="fa-solid fa-cart-plus"></i>

                Agregar al carrito

            </button>

        `;


        contenedor.appendChild(tarjeta);

    });

}


/* =========================================================
                    AGREGAR AL CARRITO
========================================================= */

function agregarAlCarritoCategoria(
    id,
    nombre,
    precio,
    imagen
) {

    let carrito =
        JSON.parse(
            localStorage.getItem("carrito")
        ) || [];


    const productoExistente =
        carrito.find(
            producto => producto.id === id
        );


    if (productoExistente) {

        productoExistente.cantidad++;

    } else {

        carrito.push({

            id: id,

            nombre: nombre,

            precio: precio,

            imagen: imagen,

            cantidad: 1

        });

    }


    /* Guardar carrito */

    localStorage.setItem(
        "carrito",
        JSON.stringify(carrito)
    );


    /* Actualizar contador */

    actualizarContadorCategoria();


    /* Mensaje */

    alert(
        `${nombre} fue agregado al carrito.`
    );

}


/* =========================================================
                ACTUALIZAR CONTADOR
========================================================= */

function actualizarContadorCategoria() {

    const contador =
        document.getElementById(
            "contadorCarrito"
        );


    if (!contador) return;


    const carrito =
        JSON.parse(
            localStorage.getItem("carrito")
        ) || [];


    const cantidad =
        carrito.reduce(
            (total, producto) =>
                total + producto.cantidad,
            0
        );


    contador.textContent =
        cantidad;

}


